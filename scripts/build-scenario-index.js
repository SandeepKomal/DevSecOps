// Builds site/scenario-index.js: a small index of the playground's scenarios
// (id, title, group, level, story), the number of quiz questions and the names
// of the X-ray examples, so the first screen (the stats, the path's practise
// links and the on-call shift) can be drawn before the simulator, the scenarios,
// the quiz bank and the X-ray have loaded.
// Run with: node scripts/build-scenario-index.js   (tests/check_playground.js keeps it in sync)
"use strict";
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const file = path.join(root, "site/scenario-index.js");

function render() {
  if (!globalThis.window) globalThis.window = {};
  for (const f of ["rules", "repo", "sim", "shell", "scenarios", "xray-explain", "quiz-bank"]) {
    const p = path.join(root, "site", f + ".js");
    delete require.cache[p];
    require(p);
  }
  const pick = (k) => globalThis.window[k] || globalThis[k];
  const list = pick("DSScenarios").SCENARIOS.map((s) => ({ id: s.id, title: s.title, group: s.group, level: s.level, story: s.story }));
  const quiz = Object.values(pick("TRACK_QUIZ")).flat().length;
  const examples = pick("DSExplain").EXAMPLES.map((ex) => ex.name);
  return `// Generated by scripts/build-scenario-index.js from site/scenarios.js, site/quiz-bank.js and site/xray-explain.js. Do not edit.
"use strict";
window.TRACK_QUIZ_COUNT = ${quiz};
window.TRACK_XRAY_EXAMPLES = ${JSON.stringify(examples)};
window.TRACK_SCENARIOS = ${JSON.stringify(list, null, 1)};
`;
}

if (require.main === module) {
  fs.writeFileSync(file, render());
  console.log(`wrote ${path.relative(root, file)}`);
}
module.exports = { render, file };
